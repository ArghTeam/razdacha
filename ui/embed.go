// Package ui встраивает собранный интерфейс панели в бинарник демона.
//
// Сборки в привычном смысле нет: `ui/dist` — это уже готовая статика (HTML, CSS
// и ES-модули без сборщика), которая лежит в репозитории и уезжает в бинарник
// как есть. Причина в tasks/22-ui.md: SvelteKit требует node, node в цепочке
// сборки демона нет, а панель обязана собираться одной командой `go build`.
//
// Каталог всегда содержит `.gitkeep`, поэтому директива go:embed не остаётся без
// файлов и сборка не ломается, даже если статику вычистили. Что делать с пустым
// каталогом, решает слой api: он отвечает понятной ошибкой, а не паникует.
package ui

import (
	"embed"
	"io/fs"
)

// all: нужен ради `.gitkeep` — без префикса go:embed пропускает файлы с точки,
// и на пустом каталоге директива стала бы ошибкой компиляции.
//
//go:embed all:dist
var dist embed.FS

// Files отдаёт содержимое `ui/dist` с корнем в самом каталоге: обработчику
// нужен путь `index.html`, а не `dist/index.html`.
func Files() fs.FS {
	sub, err := fs.Sub(dist, "dist")
	if err != nil {
		// Каталог `dist` встроен этим же пакетом, промахнуться здесь нечем:
		// ошибка означала бы испорченный бинарник.
		panic("ui: каталог dist не встроен: " + err.Error())
	}
	return sub
}
