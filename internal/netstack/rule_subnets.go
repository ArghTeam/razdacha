package netstack

import "github.com/ArghTeam/razdacha/internal/store"

// RuleMarksSubnets — попадают ли подсети правила в сет `razdacha_subnets`.
//
// Действие правила здесь не проверяется, и это решение, а не упущение. Метка
// nft не выбирает судьбу пакета — она только заводит его в sing-box, где судьбу
// выбирают `route.rules[]`. Значит вопрос «метить или нет» — это вопрос «должен
// ли пакет доехать до правил», и для действий он звучит так:
//
//   - tunnel: обязан. FakeIP срабатывает, только когда клиент резолвит домен; на
//     подсеть клиент идёт настоящим адресом, и без метки трафик уходит мимо
//     туннеля.
//   - block: обязан. `action = block` превращается в `reject` в двух наборах
//     правил sing-box (`internal/singbox/generate.go`, `routeRule` и
//     `dnsRuleFor`), но отбросить пакет он может, только если тот до него
//     доехал. Без метки блокировка по подсети молча не работает — это issue
//     #126, и ровно тот же довод уже записан в `lists.Sources`
//     (`internal/lists/manager.go`), где списки берутся с любым действием.
//   - direct: не обязан — непомеченный пакет и так уходит напрямую, метка ведёт
//     его в sing-box лишь затем, чтобы `direct-out` вернул его тем же путём.
//     Крюк через tproxy — цена, и она здесь заплачена сознательно. Причина:
//     вторая половина сета приходит из слоя lists, а `Manager.Subnets()` —
//     плоское объединение кэша без действия правила, отфильтровать `direct` там
//     нечем. Списки правила `direct` метятся сегодня и будут метиться дальше;
//     выбросив его ручные подсети, мы бы получили для `direct` ровно ту
//     асимметрию «список работает, ручная подсеть нет», из-за которой заведён
//     #126. Одно правило для всех действий дешевле, чем два разных источника
//     истины про одно и то же правило.
//
// Отсюда же следует, что «упростить обратно» до `r.Action == ActionTunnel`
// нельзя: это возвращает #126.
func RuleMarksSubnets(r store.Rule) bool {
	return r.Enabled
}
